def extract_from_table_soup(
    tbl_soup: BeautifulSoup,
    table_id: str,
    edgar_url: str,
    scale: int,
    metric_name: str,
    target_synonyms: List[str]
) -> Optional[Dict[str, Any]]:
    """Finds matching row and extracts current (col 0) and prior (col 1) numeric cells."""
    rows = tbl_soup.find_all("tr")
    for syn in target_synonyms:
        for r_idx, tr in enumerate(rows):
            cells = tr.find_all(["td", "th"])
            if not cells:
                continue
            row_txt = " ".join([c.get_text(" ", strip=True) for c in cells]).lower()

            if syn in row_txt:
                if metric_name == "total_assets" and "current assets" in row_txt:
                    continue
                if metric_name == "total_liabilities" and ("current liabilities" in row_txt or "liabilities and" in row_txt):
                    continue
                if metric_name == "shareholders_equity" and "liabilities and" in row_txt:
                    continue
                if metric_name == "diluted_eps" and "basic" in row_txt and "diluted" not in row_txt:
                    continue

                extracted_nums = []
                for c_idx, td in enumerate(cells):
                    raw_val = td.get_text(" ", strip=True)
                    num = parse_financial_number(raw_val)
                    if num is not None:
                        extracted_nums.append((num, c_idx, raw_val))

                if extracted_nums:
                    val_curr = extracted_nums[0][0]
                    col_curr = extracted_nums[0][1]
                    val_prior = extracted_nums[1][0] if len(extracted_nums) > 1 else None

                    effective_scale = 1 if metric_name == "diluted_eps" else scale
                    dollars_curr = val_curr * effective_scale if val_curr is not None else None
                    dollars_prior = val_prior * effective_scale if val_prior is not None else None

                    return {
                        "metric": metric_name,
                        "value_current": val_curr,
                        "value_prior": val_prior,
                        "dollars_current": dollars_curr,
                        "dollars_prior": dollars_prior,
                        "scale": effective_scale,
                        "snippet_text": " | ".join([c.get_text(" ", strip=True) for c in cells if c.get_text(strip=True)]),
                        "snippet_html": str(tr),
                        "source_ref": {
                            "table_id": table_id,
                            "row": r_idx,
                            "col": col_curr,
                            "edgar_url": edgar_url
                        }
                    }
    return None

def extract_rules_from_statements(located: Dict[str, Any]) -> Dict[str, Any]:
    extracted = {}

    bs_info = located.get("balance_sheet")
    is_info = located.get("income_statement")
    cf_info = located.get("cash_flow")

    bs_soup = BeautifulSoup(bs_info["table_html"], "lxml") if bs_info else None
    is_soup = BeautifulSoup(is_info["table_html"], "lxml") if is_info else None
    cf_soup = BeautifulSoup(cf_info["table_html"], "lxml") if cf_info else None

    # BS metrics
    if bs_soup and bs_info:
        for m in ["total_assets", "total_liabilities", "shareholders_equity"]:
            res = extract_from_table_soup(bs_soup, bs_info["table_id"], bs_info["edgar_url"], bs_info["scale"], m, SYNONYMS[m])
            if res:
                extracted[m] = res

    # IS metrics
    if is_soup and is_info:
        for m in ["revenue", "gross_profit", "net_income", "diluted_eps"]:
            res = extract_from_table_soup(is_soup, is_info["table_id"], is_info["edgar_url"], is_info["scale"], m, SYNONYMS[m])
            if res:
                extracted[m] = res

    # CF metrics
    if cf_soup and cf_info:
        res = extract_from_table_soup(cf_soup, cf_info["table_id"], cf_info["edgar_url"], cf_info["scale"], "operating_cash_flow", SYNONYMS["operating_cash_flow"])
        if res:
            extracted["operating_cash_flow"] = res

    return extracted

async def extract_rules_node(state: Dict[str, Any]) -> Dict[str, Any]:
    run_id = state.get("run_id", "")
    if is_node_completed(run_id, "extract_rules"):
        await event_bus.emit("node_skipped", {"node": "extract_rules", "reason": "already_done"}, run_id=run_id)
        return {}

    record_node_start(run_id, "extract_rules")
    await event_bus.emit("node_started", {"node": "extract_rules"}, run_id=run_id)

    located = state.get("located_statements", {})
    extracted = extract_rules_from_statements(located)

    record_node_finish(run_id, "extract_rules", "done")
    await event_bus.emit("node_completed", {"node": "extract_rules", "summary": f"Extracted {len(extracted)} metrics via rules"}, run_id=run_id)

    return {"rules_metrics": extracted}
